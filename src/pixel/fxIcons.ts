import type { Px } from "@/pixel/draw";

// Each effect has a unique 1-bit icon drawn as polylines on a 16x12 grid (MS-50G style).
type Pt = [number, number];
const sine = (y: number, a: number, cyc: number, x0 = 0, x1 = 15): Pt[] => Array.from({ length: x1 - x0 + 1 }, (_, i) => [x0 + i, Math.round(y - a * Math.sin((i / (x1 - x0)) * cyc * Math.PI * 2))]);
