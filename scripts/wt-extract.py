# One-time offline extractor: AKWF-FREE (CC0) single-cycle WAVs -> 64 harmonic magnitudes per keyframe.
# Writes src/audio/wtFactoryData.ts. Run: python scripts/wt-extract.py
import io, json, urllib.request, wave, numpy as np
BASE = "https://raw.githubusercontent.com/KristofferKarlAxelEkstrand/AKWF-FREE/master/AKWF"
NH = 64
# slug: (folder, first, last, pick) pick = "spread" | "low" | "high"
JOBS = {
  "rhodes-tine": ("epiano", 1, 36, "spread"), "wurly-reed": ("epiano", 37, 73, "spread"),
  "clavinet": ("clavinet", 1, 33, "spread"),
  "vowel-talk": ("hvoice", 1, 52, "spread"), "choir-vox": ("hvoice", 53, 104, "spread"),
  "fm-bass": ("fmsynth", 1, 122, "low"), "fm-growl": ("fmsynth", 1, 122, "high"),
  "lofi-8bit": ("bitreduced", 1, 68, "spread"),
}
cache = {}
def mags(folder, i):
  k = (folder, i)
  if k in cache: return cache[k]
  raw = urllib.request.urlopen(f"{BASE}/AKWF_{folder}/AKWF_{folder}_{i:04d}.wav").read()
  w = wave.open(io.BytesIO(raw)); n = w.getnframes(); ch = w.getnchannels(); sw = w.getsampwidth()
  x = np.frombuffer(w.readframes(n), dtype={1: np.uint8, 2: np.int16}[sw]).astype(float)
  x = x.reshape(-1, ch).mean(1); x -= x.mean()
  a = np.abs(np.fft.rfft(x))[1:NH + 1]; e = np.sqrt((a * a).sum()); a = a / e if e else a
  cache[k] = a; return a
out = {}
for slug, (folder, lo, hi, pick) in JOBS.items():
  ms = []
  for i in range(lo, hi + 1):
    try: ms.append((i, mags(folder, i)))
    except Exception: pass
  cen = lambda a: float((np.arange(1, NH + 1) * a * a).sum())
  ms.sort(key=lambda t: cen(t[1]))
  if pick == "low": sel = ms[:16:5][:4]
  elif pick == "high": sel = ms[-16::5][:4]
  else: sel = [ms[round(q * (len(ms) - 1))] for q in (0, 1/3, 2/3, 1)]
  out[slug] = {"src": f"AKWF_{folder} " + ",".join(f"{i:04d}" for i, _ in sel),
               "shapes": [[round(float(v), 5) for v in a] for _, a in sel]}
  print(slug, out[slug]["src"])
with open("src/audio/wtFactoryData.ts", "w") as f:
  f.write("// Generated by scripts/wt-extract.py from AKWF-FREE (CC0, Adventure Kid). Harmonics 1..64, unit energy.\n")
  f.write("export const CAPTURED: Record<string, { src: string; shapes: number[][] }> = " + json.dumps(out) + ";\n")
